function t(key, values = {}) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

function apiErrorMessage(status, data) {
  const detail = typeof data.detail === "string" ? data.detail : "";
  if (data.review_required) return t("reviewRequired");
  if (status === 401) return t("invalidToken");
  if (status === 403) return t("forbidden");
  if (status === 422) return t("invalidInput");
  if (status >= 500) return t("serviceUnavailable");
  if (locale === "en" && detail) return detail;
  if (/budget|quota/i.test(detail)) return t("dailyBudget");
  if (/stale|changed|expired/i.test(detail)) return t("stalePreview");
  if (/unresolved/i.test(detail)) return t("unresolved");
  if (/uncertain|clarify|unambiguous|needs review/i.test(detail)) return t("reviewRequired");
  return t("invalidInput");
}

function errorMessage(error) {
  if (error instanceof SyntaxError) return t("invalidJson");
  if (error instanceof TypeError) return t("networkError");
  return error.message || t("operationFailed");
}

